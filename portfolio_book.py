def _ensure_once(get_conn):
    if st.session_state.get("_book_tables_ok"):
        return True
    try:
        ensure_tables(get_conn)
        st.session_state["_book_tables_ok"] = True
        return True
    except Exception as e:  # noqa: BLE001
        st.error("새 테이블을 준비하지 못했습니다(기존 데이터는 그대로입니다): " + str(e)[:150])
        return False


def _now():
    return datetime.now(timezone.utc).isoformat()


def _yf_symbol(t):
    t = str(t).strip().upper()
    if t in ("BRKB", "BRK B"):
        return "BRK-B"
    return t if t.endswith((".KS", ".KQ")) else t.replace(".", "-")


_norm = _yf_symbol  # 기업 상태·판단 기록의 종목 키(BRK.B 와 BRK-B 를 같게 본다)


