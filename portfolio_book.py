# ---------------------------------------------------------------- DB helpers
def _run(get_conn, sql, params=None, fetch=False):
    with get_conn() as con:
        with con.cursor() as cur:
            cur.execute(sql, params or ())
            if fetch:
                cols = [d[0] for d in cur.description]
                return pd.DataFrame(cur.fetchall(), columns=cols)
    return None


def ensure_tables(get_conn):
    """새 테이블만 추가한다(이미 있으면 아무 일도 하지 않음). 기존 데이터는 지우지 않는다."""
    stmts = [
        """CREATE TABLE IF NOT EXISTS us_positions (
               ticker TEXT PRIMARY KEY, name TEXT NOT NULL DEFAULT '',
               quantity DOUBLE PRECISION NOT NULL DEFAULT 0, avg_cost DOUBLE PRECISION NOT NULL DEFAULT 0,
               mode TEXT NOT NULL DEFAULT '적립형', note TEXT NOT NULL DEFAULT '', updated_at TEXT)""",
        """CREATE TABLE IF NOT EXISTS us_buys (
               id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, created_at TEXT, ticker TEXT,
               quantity DOUBLE PRECISION, price DOUBLE PRECISION, kind TEXT, note TEXT)""",
        """CREATE TABLE IF NOT EXISTS stance_log (
               id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, created_at TEXT, ticker TEXT,
               stance TEXT, as_of TEXT, memo TEXT, invalidation TEXT)""",
        """CREATE TABLE IF NOT EXISTS holding_modes (ticker TEXT PRIMARY KEY, mode TEXT NOT NULL DEFAULT '핵심 장기')""",
        "ALTER TABLE decisions ADD COLUMN IF NOT EXISTS context TEXT",
    ]
    for s in stmts:
        _run(get_conn, s)


def _ensure_once(get_conn):
    if st.session_state.get("_book_tables_ok"):
        return True
    try:
        ensure_tables(get_conn)
        st.session_state["_book_tables_ok"] = True
        return True
    except Exception as e:  # noqa: BLE001
        st.error("새 테이블을 준비하지 못했습니다(기존 데이터는 그대로입니다): " + str(e)[:150])
        return False


def _now():
    return datetime.now(timezone.utc).isoformat()


def _yf_symbol(t):
    t = str(t).strip().upper()
    return t if t.endswith((".KS", ".KQ")) else t.replace(".", "-")


# ---------------------------------------------------------------- 읽기 규칙
def latest_stances(get_conn):
    try:
        df = _run(get_conn, "SELECT * FROM stance_log ORDER BY id DESC", fetch=True)
    except Exception:  # noqa: BLE001
        return {}
    out = {}
    for _, r in df.iterrows():
        out.setdefault(str(r["ticker"]).upper(), r)
    return out


def _stance_view(rec):
    """-> (표시 문구, 기업 상태 값, 오래됨 여부)"""
    if rec is None:
        return "미기록", "미확인", False
    st_val = str(rec["stance"])
    stale = False
    txt = st_val
    try:
        d = date.fromisoformat(str(rec["as_of"])[:10])
        age = (date.today() - d).days
        txt = "{} ({} 기준)".format(st_val, d.isoformat())
        stale = age > STANCE_STALE_DAYS
        if stale:
            txt += " · 오래됨"
    except Exception:  # noqa: BLE001
        pass
    return txt, st_val, stale


