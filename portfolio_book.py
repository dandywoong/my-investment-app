def latest_stances(get_conn):
    try:
        df = _run(get_conn, "SELECT * FROM stance_log ORDER BY id DESC", fetch=True)
    except Exception:  # noqa: BLE001
        return {}
    out = {}
    for _, r in df.iterrows():
        out.setdefault(_norm(r["ticker"]), r)
    return out


def _stance_view(rec):
    """-> (표시 문구, 기업 상태 값, 오래됨 여부)"""
    if rec is None:
        return "미기록", "미확인", False
    st_val = str(rec["stance"])
    stale = False
    txt = st_val
    try:
        d = date.fromisoformat(str(rec["as_of"])[:10])
        age = (date.today() - d).days
        txt = "{} ({} 기준)".format(st_val, d.isoformat())
        stale = age > STANCE_STALE_DAYS
        if stale:
            txt += " · 오래됨"
    except Exception:  # noqa: BLE001
        pass
    return txt, st_val, stale


def _effective(user_rec, ai):
    """-> (표시 문구, 기업 상태 값, 오래됨 여부). 내 기록과 AI 분석 중 더 최근 것을 쓰되, AI는 검색 근거가 있고 신뢰도가 낮음이 아니며 7일 이내일 때만."""
    u_txt, u_val, u_stale = _stance_view(user_rec)
    if ai is not None:
        try:
            created = datetime.fromisoformat(str(ai["created_at"]))
            age = (datetime.now(timezone.utc) - created).days
            newer = user_rec is None or str(ai["created_at"]) > str(user_rec["created_at"])
            if bool(int(ai["applied"] or 0)) and age <= 7 and newer:
                return "{} · AI {} (신뢰 {})".format(ai["stance"], created.strftime("%m-%d"), ai["confidence"]), str(ai["stance"]), False
        except Exception:  # noqa: BLE001
            pass
    return u_txt, u_val, u_stale


