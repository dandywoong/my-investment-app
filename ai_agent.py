STANCES = ["견고", "보통", "훼손", "미확인"]
FRESH_HOURS = 20          # 이 시간 안에 분석했으면 다시 하지 않는다
APPLY_MAX_AGE_DAYS = 7    # AI 결과를 행동 후보에 반영하는 최대 나이
API = "https://generativelanguage.googleapis.com/v1beta"

CREATE_SQL = """CREATE TABLE IF NOT EXISTS ai_company_view (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, created_at TEXT, ticker TEXT, stance TEXT, as_of TEXT,
    confidence TEXT, grounded INTEGER, applied INTEGER, model TEXT, summary TEXT, sources TEXT, payload TEXT)"""


def _now():
    return datetime.now(timezone.utc).isoformat()


def _run(get_conn, sql, params=None, fetch=False):
    with get_conn() as con:
        with con.cursor() as cur:
            cur.execute(sql, params or ())
            if fetch:
                cols = [d[0] for d in cur.description]
                return pd.DataFrame(cur.fetchall(), columns=cols)
    return None


def ensure_table(get_conn):
    _run(get_conn, CREATE_SQL)


def get_api_key():
    try:
        key = st.secrets.get("GEMINI_API_KEY", "")
    except Exception:  # noqa: BLE001
        key = ""
    return key or os.getenv("GEMINI_API_KEY", "")


# ---------------------------------------------------------------- 모델 고르기 (이름을 추측하지 않고 목록에서 고른다)
@st.cache_data(ttl=86400, show_spinner=False)
def _list_models(key):
    import requests
    r = requests.get(API + "/models", params={"key": key, "pageSize": 200}, timeout=20)
    r.raise_for_status()
    return r.json().get("models", [])


def pick_models(key):
    try:
        override = st.secrets.get("GEMINI_MODEL", "")
    except Exception:  # noqa: BLE001
        override = ""
    if override:
        return [override]
    models = _list_models(key)
    cands = []
    for m in models:
        name = str(m.get("name", "")).replace("models/", "")
        if "generateContent" not in (m.get("supportedGenerationMethods") or []):
            continue
        low = name.lower()
        if "flash" not in low or any(x in low for x in ("tts", "live", "image", "audio", "embed", "native", "robotics", "computer", "lite")):
            continue
        ver = re.search(r"(\d+(?:\.\d+)?)", low)
        v = float(ver.group(1)) if ver else 0.0
        stable = not any(x in low for x in ("preview", "exp", "-0"))
        cands.append((stable, v, name))
    cands.sort(reverse=True)
    return [n for _, _, n in cands[:3]]


