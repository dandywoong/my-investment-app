"""Eggfolio AI 기업 분석 (Gemini 무료 키 사용). 읽기·기록용이며 주문 기능은 없다.

- 보내는 것: 종목명·티커·시장·가격 국면 라벨·60일 고점 대비·이전 기업 상태 기록(근거 메모 포함).
  보내지 않는 것: 보유 수량, 평단, 평가금액 등 개인 자산 정보.
- 무료 키는 입력 내용이 구글의 서비스 개선에 쓰일 수 있고 사람이 검토할 수 있다. 메모에 개인 정보를 적지 않는다.
- AI 결과는 '초안'이다. 검색 근거가 있고 신뢰도가 '낮음'이 아닐 때만 행동 후보에 자동 반영되며, 언제든 내 기록으로 덮어쓸 수 있다.
- 숫자 계산(평단·가격대·국면)은 AI가 아니라 코드가 한다.
"""
import json
