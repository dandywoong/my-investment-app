def _extract_json(text):
    a, b = text.find("{"), text.rfind("}")
    if a < 0 or b <= a:
        raise ValueError("JSON 응답을 찾지 못했습니다")
    return json.loads(text[a:b + 1])


_NO_THINK = {}  # 모델별로 '생각 줄이기' 설정이 거부되면 기억해서 다시 보내지 않는다


def _call(key, model, prompt, grounded):
    import requests
    body = {"contents": [{"parts": [{"text": prompt}]}], "generationConfig": {"temperature": 0.2}}
    if grounded:
        body["tools"] = [{"google_search": {}}]
    url = "{}/models/{}:generateContent".format(API, model)
    to = 75 if grounded else 50
    if not _NO_THINK.get(model):
        fast = {"contents": body["contents"], "generationConfig": {"temperature": 0.2, "thinkingConfig": {"thinkingBudget": 0}}}
        if grounded:
            fast["tools"] = body["tools"]
        r = requests.post(url, params={"key": key}, json=fast, timeout=to)
        if r.status_code == 400 and "think" in r.text.lower():
            _NO_THINK[model] = True
        else:
            return r
    return requests.post(url, params={"key": key}, json=body, timeout=to)


def _err_text(r):
    try:
        e = r.json().get("error", {})
        msg = str(e.get("message", ""))[:200]
        delay = ""
        for d in e.get("details", []):
            if isinstance(d, dict) and d.get("retryDelay"):
                delay = str(d["retryDelay"])
        return msg + (" (재시도 권장 {})".format(delay) if delay else "")
    except Exception:  # noqa: BLE001
        return r.text[:200].replace("\n", " ")


def analyze_one(key, models, t):
    """-> (결과 dict | None, 오류 문구 | None, 429 여부). 검색 근거를 먼저 시도하고, 429나 오류면 근거 없이, 그다음 다음 모델로 넘어간다."""
    use_search = False
    try:
        use_search = str(st.secrets.get("GEMINI_SEARCH", "")).strip() in ("1", "true", "True")
    except Exception:  # noqa: BLE001
        use_search = False
    packet, n_dated = None, 0
    try:
        packet, n_dated = gather_packet(t["tk"])
    except Exception:  # noqa: BLE001
        packet, n_dated = None, 0
    packet_ok = bool(packet) and (n_dated >= 2 or len((packet or {}).get("info", {})) >= 8)
    prompt = _prompt(t, packet if packet_ok else None)
    last, saw429 = None, False
    for model in models:
        for grounded in ((True, False) if (use_search or not packet_ok) else (False,)):
            try:
                r = _call(key, model, prompt, grounded)
            except Exception as e:  # noqa: BLE001
                last = "연결 오류: " + str(e)[:100]
                continue
            if r.status_code >= 400:
                if r.status_code == 429:
                    saw429 = True
                last = "{} {} [모델 {}{}]".format(r.status_code, _err_text(r), model, " · 검색 근거" if grounded else "")
                continue
            try:
                data = r.json()
                cand = data["candidates"][0]
                text = "".join(p.get("text", "") for p in cand["content"]["parts"])
                res = _extract_json(text)
            except Exception as e:  # noqa: BLE001
                last = "응답 해석 실패: " + str(e)[:100]
                continue
            gm = cand.get("groundingMetadata") or {}
            chunks = gm.get("groundingChunks") or []
            sources = [{"title": (c.get("web") or {}).get("title", ""), "uri": (c.get("web") or {}).get("uri", "")} for c in chunks][:8]
            if not sources and packet_ok:
                sources = [{"title": "{} {}".format(n["publisher"], n["date"]).strip() or n["title"][:30], "uri": n["url"]} for n in packet["news"] if n["url"]][:8]
            res["_sources"] = sources
            res["_grounded"] = bool(sources) or bool(packet_ok and n_dated >= 2)
            res["_basis"] = "검색" if (grounded and gm) else ("야후 뉴스·재무 자료" if packet_ok else "근거 없음")
            res["_model"] = model
            return res, None, False
    return None, last or "알 수 없는 오류", saw429


def diagnose(key):
    """연결 진단(빠름): 쓸 수 있는 모델, 일반 호출 1회, 야후 자료 수집 확인."""
    rows = []
    try:
        models = pick_models(key)
    except Exception as e:  # noqa: BLE001
        return [{"항목": "모델 목록", "결과": "실패: " + str(e)[:150]}]
    rows.append({"항목": "쓸 수 있는 모델", "결과": ", ".join(models) or "없음"})
    if models:
        try:
            r = _call(key, models[0], "한 단어로 '확인'이라고만 답하세요.", False)
            rows.append({"항목": "일반 호출 ({})".format(models[0]), "결과": "정상" if r.status_code < 400 else "{} {}".format(r.status_code, _err_text(r))})
        except Exception as e:  # noqa: BLE001
            rows.append({"항목": "일반 호출", "결과": "연결 오류 " + str(e)[:100]})
    try:
        pk, nd = gather_packet("AAPL")
        rows.append({"항목": "야후 자료 수집(AAPL 시험)", "결과": "뉴스 {}건(날짜 있음 {}) · 재무 항목 {}개".format(len(pk["news"]), nd, len(pk["info"]))})
    except Exception as e:  # noqa: BLE001
        rows.append({"항목": "야후 자료 수집", "결과": "실패: " + str(e)[:100]})
    return rows


def _clean(res):
    st_ = str(res.get("stance", "미확인"))
    res["stance"] = st_ if st_ in STANCES else "미확인"
    conf = str(res.get("confidence", "낮음"))
    res["confidence"] = conf if conf in ("낮음", "보통", "높음") else "낮음"
    return res


def save_result(get_conn, tk, res):
    res = _clean(res)
    applied = int(bool(res.get("_grounded")) and res["confidence"] != "낮음" and res["stance"] != "미확인")
    _run(get_conn, """INSERT INTO ai_company_view (created_at,ticker,stance,as_of,confidence,grounded,applied,model,summary,sources,payload)
                      VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s)""",
         (_now(), tk, res["stance"], str(res.get("as_of", ""))[:10], res["confidence"], int(bool(res.get("_grounded"))), applied,
          str(res.get("_model", "")), str(res.get("summary", ""))[:1500], json.dumps(res.get("_sources", []), ensure_ascii=False),
          json.dumps(res, ensure_ascii=False)))
    return applied


def _safe_analyze(key, models, t):
    try:
        return analyze_one(key, models, t)
    except Exception as e:  # noqa: BLE001
        return None, "예상치 못한 오류: " + str(e)[:100], False


RETRY_UNAPPLIED_HOURS = 6   # 근거 부족으로 '반영 안 됨'이 된 종목은 이 시간 안에는 다시 시도하지 않는다(같은 종목만 반복 분석되는 것을 막음)


def _attempt_age(row):
    """마지막 시도 후 경과 시간(시간). 기록이 없으면 None."""
    if row is None:
        return None
    try:
        return (datetime.now(timezone.utc) - datetime.fromisoformat(str(row["created_at"]))).total_seconds() / 3600
    except Exception:  # noqa: BLE001
        return None


def status_text(row):
    if row is None:
        return "분석 기록 없음"
    ag = _attempt_age(row)
    ag_txt = "" if ag is None else "{:.0f}시간 전 ".format(ag)
    return "{}{} · {}".format(ag_txt, row["stance"], "행동 후보에 반영" if int(row["applied"] or 0) else "근거 부족(반영 안 됨)")


def queue(targets, ai_views):
    """분석 순서. 분석할 가치가 있는 종목부터: 종합 점수(오늘 사고 싶은 순위)가 높은 종목 → 같으면 마지막 분석이 오래된 종목.
    제외: 20시간 안에 반영된 분석이 있는 종목, 6시간 안에 시도했지만 근거 부족으로 끝난 종목(반복 방지). -> [(target, 사유 문구)]"""
    out = []
    for t in targets:
        row = ai_views.get(t["tk"])
        ag = _attempt_age(row)
        if row is not None and ag is not None:
            if int(row["applied"] or 0) and ag < FRESH_HOURS:
                continue
            if not int(row["applied"] or 0) and ag < RETRY_UNAPPLIED_HOURS:
                continue
        out.append((t, status_text(row)))
    return sorted(out, key=lambda x: (-(x[0].get("score") or 0), -(_attempt_age(ai_views.get(x[0]["tk"])) or 1e9)))


def refresh(get_conn, targets, ai_views, max_n=4, sleep_s=3, force_tks=None):
    """오래된 순으로 최대 max_n 종목을 분석해 저장한다. 한 종목이 실패해도 다음으로 넘어가며 앱이 멈추지 않는다.
    -> (처리 목록, 오류 목록, 변화 목록)"""
    key = get_api_key()
    if not key:
        return [], ["GEMINI_API_KEY 가 설정되지 않았습니다."], []
    try:
        models = pick_models(key)
    except Exception as e:  # noqa: BLE001
        return [], ["모델 목록을 가져오지 못했습니다(키를 확인하세요): " + str(e)[:120]], []
    if not models:
        return [], ["이 키로 쓸 수 있는 flash 모델을 찾지 못했습니다."], []
    if force_tks:
        todo = [t for t in targets if t["tk"] in force_tks]
    else:
        todo = [t for t, _ in queue(targets, ai_views)[:max_n]]
    done, errs, changes = [], [], []
    bar = st.progress(0.0, text="AI 분석 준비 중... (한 번에 2개씩 동시에 분석합니다)")
    from concurrent.futures import ThreadPoolExecutor
    results = []
    with ThreadPoolExecutor(max_workers=2) as ex:
        futs = []
        for t in todo:
            futs.append((t, ex.submit(_safe_analyze, key, models, t)))
        for i, (t, f) in enumerate(futs):
            bar.progress(i / max(len(todo), 1), text="{} 결과 기다리는 중... ({}/{})".format(t["name"], i + 1, len(todo)))
            results.append((t, f.result()))
    rate_n = 0
    for t, (res, err, rate) in results:
        if err:
            rate_n += 1 if rate else 0
            errs.append("{}: {}".format(t["name"], err) + (" — 무료 한도(429)입니다. 잠시 대기 후 다시 눌러 주세요." if rate else ""))
            continue
        prev = ai_views.get(t["tk"])
        try:
            applied = save_result(get_conn, t["tk"], res)
        except Exception as e:  # noqa: BLE001
            errs.append("{}: 저장 실패 {}".format(t["name"], str(e)[:100]))
            continue
        done.append(t["name"])
        new_st = _clean(res)["stance"]
        old_st = prev["stance"] if prev is not None else (t.get("prior") or {}).get("stance", "없음")
        if new_st != old_st:
            changes.append("{}: {} → {}{}".format(t["name"], old_st, new_st, "" if applied else " (근거 부족 · 참고만)"))
    if rate_n >= 2:
        errs.append("한도 초과가 반복되었습니다. 몇 분 뒤(하루 한도면 내일) 다시 시도하세요. '🔎 AI 연결 진단'으로 원인을 볼 수 있습니다.")
    bar.progress(1.0, text="완료")
    return done, errs, changes


def load_views(get_conn):
    try:
        df = _run(get_conn, "SELECT * FROM ai_company_view ORDER BY id DESC", fetch=True)
    except Exception:  # noqa: BLE001
        return {}
    out = {}
    for _, r in df.iterrows():
        out.setdefault(str(r["ticker"]).upper(), r)
    return out


def render_view(row):
    """종목 상세에 AI 분석 한 건을 보여 준다."""
    if row is None:
        st.info("아직 AI 분석이 없습니다. 위의 '🤖 AI 기업 분석 갱신'을 눌러 주세요.")
        return
    try:
        p = json.loads(row["payload"])
    except Exception:  # noqa: BLE001
        p = {}
    st.markdown("**🤖 AI 기업 분석 (초안 · 검증 전)**")
    st.write("판정: **{}** · 신뢰도 {} · 근거 기준일 {} · 분석 {} · 모델 {}".format(
        row["stance"], row["confidence"], row["as_of"] or "자료 없음", str(row["created_at"])[:16].replace("T", " ") + " UTC", row["model"]))
    applied = bool(int(row["applied"] or 0))
    basis = (p.get("_basis") if isinstance(p, dict) else None) or ""
    if basis:
        st.caption("분석 근거: " + basis)
    st.caption("행동 후보에 반영됨" if applied else
               "행동 후보에는 반영되지 않았습니다(검색 근거가 없거나 신뢰도가 낮거나 미확인). 참고만 하세요.")
    if p.get("summary"):
        st.write(p["summary"])
    if p.get("changed"):
        st.write("달라진 점: " + str(p["changed"]))
    if p.get("thesis_check"):
        st.write("내 이전 가설 점검: " + str(p["thesis_check"]))
    ev = p.get("evidence") or []
    if ev:
        st.dataframe(pd.DataFrame([{"사실": e.get("fact", ""), "날짜": e.get("date", ""), "출처": e.get("source", "")} for e in ev if isinstance(e, dict)]),
                     use_container_width=True, hide_index=True)
    for title, key in (("위험", "risks"), ("다음에 확인할 일", "watch"), ("확인하지 못한 것", "unknowns")):
        vals = p.get(key) or []
        if vals:
            st.write("**{}**: ".format(title) + " · ".join(str(v) for v in vals))
    if p.get("invalidation"):
        st.write("무효화 조건(AI 제안): " + str(p["invalidation"]))
    try:
        srcs = json.loads(row["sources"] or "[]")
    except Exception:  # noqa: BLE001
        srcs = []
    if srcs:
        st.caption("검색 출처: " + " · ".join("[{}]({})".format(s.get("title") or "링크", s.get("uri")) for s in srcs if s.get("uri")))
    st.caption("AI는 틀리거나 오래된 정보를 쓸 수 있습니다. 중요한 판단 전에는 원문 공시·실적으로 직접 확인하세요.")
